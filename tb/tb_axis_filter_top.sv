// ==============================================================================
// File: tb_axis_filter_top.sv
// Description: Self-checking testbench for AXI4-Stream 2D Image Convolution
//              Accelerator. Streams pixels, drives random backpressure (TREADY),
//              and validates output bit-for-bit against Python Golden Model.
// Standard: SystemVerilog IEEE 1800-2012 / 1800-2017
// ==============================================================================

`timescale 1ns / 1ps

import image_filter_pkg::*;

module tb_axis_filter_top;

  localparam int IMG_WIDTH   = 128;
  localparam int IMG_HEIGHT  = 128;
  localparam int PIXEL_WIDTH = 8;
  localparam time CLK_PERIOD = 10ns; // 100 MHz clock

  logic aclk;
  logic aresetn;
  filter_mode_t filter_mode;
  logic test_mode;

  // AXI4-Stream Slave Interface
  logic [PIXEL_WIDTH-1:0] s_axis_tdata;
  logic                   s_axis_tvalid;
  wire                    s_axis_tready;
  logic                   s_axis_tlast;
  logic                   s_axis_tuser;

  // AXI4-Stream Master Interface
  wire [PIXEL_WIDTH-1:0]  m_axis_tdata;
  wire                    m_axis_tvalid;
  logic                   m_axis_tready;
  wire                    m_axis_tlast;
  wire                    m_axis_tuser;

  // Clock Generation
  initial aclk = 1'b0;
  always #(CLK_PERIOD / 2) aclk = ~aclk;

  // Instantiate Device Under Test (DUT)
  axis_image_filter_top #(
    .IMG_WIDTH   (IMG_WIDTH),
    .IMG_HEIGHT  (IMG_HEIGHT),
    .PIXEL_WIDTH (PIXEL_WIDTH)
  ) dut (
    .aclk          (aclk),
    .aresetn       (aresetn),
    .filter_mode   (filter_mode),
    .test_mode     (test_mode),
    .s_axis_tdata  (s_axis_tdata),
    .s_axis_tvalid (s_axis_tvalid),
    .s_axis_tready (s_axis_tready),
    .s_axis_tlast  (s_axis_tlast),
    .s_axis_tuser  (s_axis_tuser),
    .m_axis_tdata  (m_axis_tdata),
    .m_axis_tvalid (m_axis_tvalid),
    .m_axis_tready (m_axis_tready),
    .m_axis_tlast  (m_axis_tlast),
    .m_axis_tuser  (m_axis_tuser)
  );

  // Verification Memories & State
  logic [7:0] input_mem [0:(IMG_WIDTH*IMG_HEIGHT)-1];
  logic [7:0] expected_mem [0:((IMG_WIDTH-2)*(IMG_HEIGHT-2))-1];

  int received_count = 0;
  int error_count    = 0;
  int total_expected = (IMG_WIDTH - 2) * (IMG_HEIGHT - 2);

  // Watchdog Timer to prevent testbench from hanging
  initial begin
    #10000000ns; // 10 ms timeout
    $display("\n[ERROR] Simulation timeout reached!");
    $display("Received %0d / %0d pixels. Mismatches so far: %0d", received_count, total_expected, error_count);
    $finish;
  end

  // --------------------------------------------------------------------------
  // Main Driver Process: Load Hex and Stream In with Handshakes
  // --------------------------------------------------------------------------
  initial begin
    aresetn       = 1'b0;
    test_mode     = 1'b0;
    filter_mode   = MODE_SOBEL_MAG;
    s_axis_tdata  = '0;
    s_axis_tvalid = 1'b0;
    s_axis_tlast  = 1'b0;
    s_axis_tuser  = 1'b0;
    m_axis_tready = 1'b1;

    // Load test patterns generated by Python golden model
    $readmemh("input_pixels.hex", input_mem);
    $readmemh("expected_pixels.hex", expected_mem);

    // Apply Reset
    #(CLK_PERIOD * 5);
    aresetn = 1'b1;
    #(CLK_PERIOD * 2);

    $display("----------------------------------------------------------------");
    $display("[TB] Starting AXI4-Stream Image Filter Verification (%0dx%0d)", IMG_WIDTH, IMG_HEIGHT);
    $display("----------------------------------------------------------------");

    // Stream pixels with simulated random backpressure
    for (int i = 0; i < IMG_WIDTH * IMG_HEIGHT; i++) begin
      @(posedge aclk);
      while (!s_axis_tready) @(posedge aclk); // Wait for pipeline ready

      s_axis_tvalid <= 1'b1;
      s_axis_tdata  <= input_mem[i];
      s_axis_tuser  <= (i == 0);
      s_axis_tlast  <= (i == (IMG_WIDTH * IMG_HEIGHT - 1));
    end

    @(posedge aclk);
    s_axis_tvalid <= 1'b0;
    s_axis_tlast  <= 1'b0;
    s_axis_tuser  <= 1'b0;

    // Wait until all filtered pixels are received and verified
    while (received_count < total_expected) @(posedge aclk);

    #(CLK_PERIOD * 10);
    $display("\n================================================================");
    $display("   FINAL VERIFICATION SUMMARY REPORT");
    $display("================================================================");
    $display("Total Pixels Streamed In:  %0d", IMG_WIDTH * IMG_HEIGHT);
    $display("Total Pixels Received Out: %0d / %0d expected", received_count, total_expected);
    $display("Total Pixel Mismatches:    %0d", error_count);

    if (error_count == 0 && received_count == total_expected) begin
      $display("\n################################################################");
      $display("###                 ALL TESTS PASSED!                        ###");
      $display("###    Hardware RTL matches Python Golden Model bit-for-bit  ###");
      $display("################################################################\n");
    end else begin
      $display("\n[ERROR] TEST FAILED WITH %0d MISMATCHES!\n", error_count);
    end

    $finish;
  end

  // --------------------------------------------------------------------------
  // Output Monitor & Scoreboard (with randomized downstream backpressure)
  // --------------------------------------------------------------------------
  always @(posedge aclk) begin
    if (!aresetn) begin
      received_count <= 0;
      error_count    <= 0;
      m_axis_tready  <= 1'b1;
    end else begin
      // Downstream receiver ready (90% ready, 10% backpressure)
      m_axis_tready <= ($urandom_range(0, 100) > 10);

      if (m_axis_tvalid && m_axis_tready) begin
        if (received_count < total_expected) begin
          if (m_axis_tdata !== expected_mem[received_count]) begin
            if (error_count < 10) begin
              $display("[MISMATCH @ pixel %0d] RTL=0x%02x != Exp=0x%02x", 
                       received_count, m_axis_tdata, expected_mem[received_count]);
            end
            error_count++;
          end
        end
        received_count++;
      end
    end
  end

  // Dump VCD waveform - only 2 levels inside DUT to keep file small & simulation fast
  initial begin
    $dumpfile("axis_filter_trace.vcd");
    $dumpvars(2, dut);
  end

endmodule
